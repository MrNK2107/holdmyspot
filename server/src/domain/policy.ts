import { createHash } from 'node:crypto';
import { HOUR } from '../clock.js';
import type { Booking, CancelReason, MessageLabel } from './types.js';

/** Typed cancellation policy. Compiled from prose by the AI, approved by the owner, enforced by code. */
export interface PolicyRules {
  /** amount held 3 days before the visit; also the hard ceiling for any charge */
  holdCents: number;
  /** cancelling at least this many hours ahead is free */
  freeCancelHours: number;
  lateCancelFeeCents: number;
  noShowFeeCents: number;
  /** reasons excused by policy (void, no fee) */
  excusedReasons: CancelReason[];
  /** how many excusals per client per window; e.g. 1 per 6 months */
  excusalLimit: { count: number; months: number };
  /** reasons where the owner always decides; never auto-charged */
  protectedReasons: CancelReason[];
  /** if the slot is refilled, the canceller pays nothing */
  refillWaives: boolean;
  /** minimum classifier confidence before the engine acts on a message */
  minConfidence: number;
}

export interface ApprovedPolicy {
  version: number;
  hash: string;
  rules: PolicyRules;
  prose: string;
  summary: string;
  approvedAt: number;
}

export const DEFAULT_RULES: PolicyRules = {
  holdCents: 2000,
  freeCancelHours: 24,
  lateCancelFeeCents: 2000,
  noShowFeeCents: 2000,
  excusedReasons: ['illness_dependent', 'illness_self'],
  excusalLimit: { count: 1, months: 6 },
  protectedReasons: ['medical_emergency', 'bereavement', 'emergency_other'],
  refillWaives: true,
  minConfidence: 0.75,
};

export function validateRules(r: PolicyRules): string[] {
  const errs: string[] = [];
  const int = (n: number) => Number.isInteger(n) && n >= 0;
  if (!int(r.holdCents) || r.holdCents === 0) errs.push('holdCents must be a positive integer');
  if (!int(r.lateCancelFeeCents) || r.lateCancelFeeCents > r.holdCents) errs.push('lateCancelFeeCents must be <= holdCents');
  if (!int(r.noShowFeeCents) || r.noShowFeeCents > r.holdCents) errs.push('noShowFeeCents must be <= holdCents');
  if (!(r.freeCancelHours >= 0 && r.freeCancelHours <= 72))
    errs.push('freeCancelHours must be 0..72: the PayPal hold is placed 72h before the visit, so a longer fee window could never be charged');
  if (!(r.minConfidence > 0 && r.minConfidence <= 1)) errs.push('minConfidence must be in (0,1]');
  if (r.excusedReasons.some((x) => r.protectedReasons.includes(x))) errs.push('a reason cannot be both excused and protected');
  return errs;
}

function canonical(v: unknown): string {
  if (Array.isArray(v)) return `[${v.map(canonical).join(',')}]`;
  if (v && typeof v === 'object') {
    return `{${Object.keys(v)
      .sort()
      .map((k) => `${JSON.stringify(k)}:${canonical((v as any)[k])}`)
      .join(',')}}`;
  }
  return JSON.stringify(v);
}

export function hashRules(r: PolicyRules): string {
  return createHash('sha256').update(canonical(r)).digest('hex').slice(0, 16);
}

const REASON_TEXT: Record<CancelReason, string> = {
  illness_self: 'you are sick',
  illness_dependent: 'your child or someone you care for is sick',
  medical_emergency: 'a medical emergency',
  bereavement: 'a death in the family',
  emergency_other: 'another emergency',
  work: 'work',
  transport: 'transport problems',
  forgot: 'forgetting',
  no_reason: 'no reason',
  none: 'none',
};

const usd = (c: number) => `$${(c / 100).toFixed(c % 100 ? 2 : 0)}`;

/** Client-facing summary, generated by code from the approved rules (not by the AI). */
export function summarize(r: PolicyRules): string {
  const lines = [
    `We place a ${usd(r.holdCents)} hold on your PayPal 3 days before your visit. It is not a charge.`,
    `Cancel ${r.freeCancelHours}+ hours ahead and the hold is released.`,
    `Later cancellations: up to ${usd(r.lateCancelFeeCents)}. No-shows: up to ${usd(r.noShowFeeCents)}.`,
  ];
  if (r.refillWaives) lines.push('If we fill your spot from the waitlist, you pay nothing.');
  if (r.excusedReasons.length) {
    lines.push(
      `Excused ${r.excusalLimit.count === 1 ? 'once' : `${r.excusalLimit.count} times`} every ${r.excusalLimit.months} months: ${r.excusedReasons
        .map((x) => REASON_TEXT[x])
        .join('; ')}.`,
    );
  }
  if (r.protectedReasons.length) lines.push('Emergencies are always reviewed by a person, never charged automatically.');
  return lines.join(' ');
}

export function approve(prev: ApprovedPolicy | undefined, rules: PolicyRules, prose: string, now: number): ApprovedPolicy {
  const errs = validateRules(rules);
  if (errs.length) throw new Error(`invalid rules: ${errs.join('; ')}`);
  return { version: (prev?.version ?? 0) + 1, hash: hashRules(rules), rules, prose, summary: summarize(rules), approvedAt: now };
}

export type Decision =
  | { outcome: 'VOID_EARLY'; why: string }
  | { outcome: 'EXCUSE'; why: string }
  | { outcome: 'PENDING_REFILL'; feeCents: number; why: string }
  | { outcome: 'OWNER_REVIEW'; suggested: 'EXCUSE' | 'PENDING_REFILL'; feeCents: number; why: string }
  | { outcome: 'CLARIFY'; why: string }
  | { outcome: 'NO_ACTION'; why: string };

export interface DecideInput {
  booking: Pick<Booking, 'start' | 'holdCents'>;
  rules: PolicyRules;
  now: number;
  kind: 'cancel' | 'no_show';
  label?: MessageLabel;
  /** excusals this client already used inside the policy window */
  priorExcusals: number;
}

/** Deterministic policy engine. The AI proposes a label; this decides. */
export function decide(i: DecideInput): Decision {
  const { rules, label } = i;
  if (i.kind === 'cancel') {
    if (!label) return { outcome: 'CLARIFY', why: 'no message label' };
    if (label.intent !== 'cancel' && label.intent !== 'reschedule') return { outcome: 'NO_ACTION', why: `intent is ${label.intent}` };
    if (label.confidence < rules.minConfidence) return { outcome: 'CLARIFY', why: `confidence ${label.confidence} below ${rules.minConfidence}` };
    const hoursAhead = (i.booking.start - i.now) / HOUR;
    if (hoursAhead >= rules.freeCancelHours) return { outcome: 'VOID_EARLY', why: `cancelled ${Math.floor(hoursAhead)}h ahead (free window ${rules.freeCancelHours}h)` };
  }
  const feeCents = Math.min(i.kind === 'cancel' ? rules.lateCancelFeeCents : rules.noShowFeeCents, rules.holdCents, i.booking.holdCents);
  const reason = label?.reason ?? 'none';
  if (rules.protectedReasons.includes(reason)) {
    return { outcome: 'OWNER_REVIEW', suggested: 'EXCUSE', feeCents, why: `protected reason (${reason}): owner decides` };
  }
  if (rules.excusedReasons.includes(reason)) {
    if (i.priorExcusals < rules.excusalLimit.count) {
      return { outcome: 'EXCUSE', why: `${reason} is excused (${i.priorExcusals + 1}/${rules.excusalLimit.count} in ${rules.excusalLimit.months} months)` };
    }
    return { outcome: 'OWNER_REVIEW', suggested: 'PENDING_REFILL', feeCents, why: `${reason} excusal already used in the last ${rules.excusalLimit.months} months` };
  }
  return { outcome: 'PENDING_REFILL', feeCents, why: i.kind === 'no_show' ? 'no-show' : `late cancel (${reason})` };
}

export interface CaptureCheck {
  amountCents: number;
  authorizedCents: number;
  rules: PolicyRules;
  label?: MessageLabel;
  ownerApproved: boolean;
  /** what the fee is for: the capture may not exceed that fee (the hold is only the outer cap) */
  kind?: 'no_show' | 'late_cancel';
}

/** Engine invariants checked immediately before every capture. Any violation blocks the capture. */
export function captureViolations(c: CaptureCheck): string[] {
  const v: string[] = [];
  if (!Number.isInteger(c.amountCents) || c.amountCents <= 0) v.push('amount must be a positive integer');
  if (c.amountCents > c.authorizedCents) v.push('amount exceeds authorized amount');
  if (c.amountCents > c.rules.holdCents) v.push('amount exceeds policy maximum');
  if (c.kind === 'no_show' && c.amountCents > c.rules.noShowFeeCents) v.push('amount exceeds the no-show fee');
  if (c.kind === 'late_cancel' && c.amountCents > c.rules.lateCancelFeeCents) v.push('amount exceeds the late-cancel fee');
  if (!c.ownerApproved) v.push('every capture needs an owner tap');
  if (c.label && c.label.confidence < c.rules.minConfidence) v.push('classifier confidence below threshold');
  if (c.label && c.rules.protectedReasons.includes(c.label.reason) && !c.ownerApproved) v.push('protected reason without owner');
  return v;
}
